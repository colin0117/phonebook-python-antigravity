import { APIRequestContext } from '@playwright/test';
import { ApiHelper, ContactPayload } from '../utils/api-helper';

export class BddFixtures {
  readonly api: ApiHelper;

  constructor(request: APIRequestContext) {
    this.api = new ApiHelper(request);
  }

  generateContactPayload(overrides: Partial<ContactPayload> = {}): ContactPayload {
    const timestamp = Date.now();
    return {
      first_name: `User${timestamp}`,
      last_name: `FixtureTest${timestamp}`,
      phone_number: `+1 (555) ${Math.floor(100 + Math.random() * 900)}-${Math.floor(1000 + Math.random() * 9000)}`,
      email: `user${timestamp}@fixture.test`,
      date_of_birth: '1990-05-15',
      category: 'Work',
      notes: 'Generated by BDD Fixture',
      ...overrides
    };
  }

  async createFixtureContact(fullName: string, phone: string): Promise<any> {
    const parts = fullName.trim().split(' ');
    const firstName = parts[0];
    const lastName = parts.slice(1).join(' ') || 'Test';

    const response = await this.api.createContact({
      first_name: firstName,
      last_name: lastName,
      phone_number: phone,
      email: `${firstName.toLowerCase()}@fixture.test`,
      date_of_birth: '1990-05-15',
      category: 'Work',
      notes: 'Automated test fixture'
    });

    return response;
  }
}
